import { open, ok, done, URL, MOCK } from './lib.mjs';
import fs from 'fs';
const { browser, page, errors } = await open('#/org/profile');
await page.evaluate(async () => {
  const st = await import('/js/state.js'); const store = await import('/js/store.js');
  const w = st.newWorkspace({ name: 'Payload test' }); w.docs = [{ id: 'doc-p1', name: 'case.txt', category: 'Business case' }];
  await store.put('blob', 'doc:doc-p1', 'Acme Clinic runs outpatient care in Montreal.');
  await st.create(w);
  const AI = await import('/js/ai.js'); AI.settings(w).acknowledged = new Date().toISOString();
});
await page.waitForTimeout(600);
const p = page.evaluate(async () => {
  const aiui = await import('/js/aiui.js'); const X = await import('/js/extractor.js'); const st = await import('/js/state.js');
  const cp = await X.corpus(st.S.ws);
  const out = await aiui.request('extract_profile', { text: cp.text }, { title: 'Profile extraction — what will be sent' });
  return out && { edited: out.edited, creativity: out.creativity, text: out.text.slice(0, 20) };
});
await page.waitForSelector('.modal textarea');
const tas = await page.$$('.modal textarea');
ok(tas.length === 2, 'two editable boxes');
ok(!(await tas[1].getAttribute('readonly')), 'request is editable');
const prompt0 = await tas[1].inputValue();
ok(/CREATIVITY: balanced/.test(prompt0), 'default creativity written into payload');
await page.selectOption('.modal select', 'creative');
const prompt1 = await tas[1].inputValue();
ok(/CREATIVITY: creative/.test(prompt1) && !/CREATIVITY: balanced/.test(prompt1), 'creativity change re-prepares payload');
ok(prompt1.indexOf('CREATIVITY') < prompt1.indexOf('DOCUMENTS:'), 'instruction placed before documents');
await tas[1].fill(prompt1 + '\nEXTRA CONTEXT FROM ANALYST: 12 clinics.');
ok(await page.isVisible('.modal .pill.warn'), 'edited pill shown');
await page.click('.modal .btnrow .btn:not(.ghost)');
const res = await p;
ok(res && res.edited === true && res.creativity === 'creative', 'result carries edited + creativity ' + JSON.stringify(res));
const last = JSON.parse(fs.readFileSync(MOCK + '/_last.json', 'utf8'));
ok(last.prompt.includes('EXTRA CONTEXT FROM ANALYST'), 'edited text is what was sent');
ok(last.temperature == null, 'no temperature for remote provider');
const log = await page.evaluate(async () => { const AI = await import('/js/ai.js'); return AI.log()[0]; });
ok(log.edited === true && log.creativity === 'creative', 'AI log records edit and level');
await page.goto(URL + '#/settings/ai'); await page.waitForTimeout(1200);
ok(await page.isVisible('text=Creativity of extraction and proposals'), 'settings field shown');
ok(errors.length === 0, 'no console error: ' + errors.join(' | '));
await browser.close(); done('t02 payload & creativity');
