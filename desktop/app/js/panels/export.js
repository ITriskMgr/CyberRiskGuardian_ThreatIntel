'use strict';
import { GENERATOR } from '../version.js';
import { el, n0, n2, card, banner, download, toast, copyText, kpi, select, field, pill, pillFor, table, money } from '../util.js';
import { S, compute, exportAssessment, docText, saveNow } from '../state.js';
